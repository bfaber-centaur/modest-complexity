#!/usr/bin/env python3
"""Run accounting for e4: every claimed run in research/e4/plan.json with its terminal
registry status, and every registry event whose run ID is not claimed (there should be none).

uv run --locked python research/e4/coordinator/runs_table.py > research/e4/coordinator/RUNS.md
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
LANES = ('dynamics', 'mechanisms', 'audit', 'coordinator')


def start(r):
    if 'resume' in r:
        return f"resume {r['resume_of']} at {r['resume_step']}"
    if 'init_weights' in r:
        return 'start file ' + Path(r['init_weights']).stem
    return 'init'


def main():
    plan = json.loads((ROOT/'research/e4/plan.json').read_text())
    events = {}
    for lane in LANES:
        path = ROOT/f'research/e4/{lane}/registry.jsonl'
        if path.exists():
            for line in path.read_text().splitlines():
                if line.strip():
                    e = json.loads(line)
                    events.setdefault(e['run_id'], []).append(dict(e, lane=lane))
    claimed = {r['run_id'] for r in plan['runs']}
    print('# e4 run accounting\n')
    print('Generated by `research/e4/coordinator/runs_table.py` from `research/e4/plan.json` and the lane registries. '
          'Status is the last registry event; "not launched" means claimed with no event. '
          'Decay: uniform wd, or wd restricted by a projection file (`rest` = reference parts exempt, `reference` = only they decay).\n')
    print('| run ID | owner | purpose | start | wd / decay | updates | status | completed | published |')
    print('|---|---|---|---|---|---|---|---|---|')
    counts, owners = {}, {}
    for r in plan['runs']:
        c = {**plan['common'], **r}
        ev = events.get(r['run_id'], [])
        last = ev[-1] if ev else {}
        status = last.get('status', 'not launched')
        counts[status] = counts.get(status, 0) + 1
        owners[r['owner']] = owners.get(r['owner'], 0) + 1
        decay = f"{c['wd']:g}" + (f" on {c['decay_on']}" if 'decay_on' in c else '')
        pub = ROOT/f"research/e4/{r['owner']}/runs/{r['run_id']}"
        print(f"| `{r['run_id']}` | {r['owner']} | {c['purpose']} | {start(r)} | {decay} | {c['steps']:,} | {status} | "
              f"{last.get('completed_steps', '')} | {'yes' if pub.exists() else 'no'} |")
    print('\nTotals: ' + ', '.join(f'{k} {v}' for k, v in sorted(counts.items())) + f' (of {len(plan["runs"])} claimed; '
          + ', '.join(f'{k} {v}' for k, v in sorted(owners.items())) + ').')
    stray = sorted(set(events) - claimed)
    print('\nRegistry events for unclaimed IDs: ' + (', '.join(f'`{s}`' for s in stray) if stray else 'none') + '.')


if __name__ == '__main__':
    main()
