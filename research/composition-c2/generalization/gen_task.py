#!/usr/bin/env python3
"""Task structure for the generalization lane: products (overall permutations) of programs of
any length, how longer programs relate to the functions supervised in training, identifiability
of the primitives from final tables, and the new-draw acceptance rule of QUESTION.md.

Convention (c2task / r1 execute): op a is applied first, so the length-L program q has the
product table pi(q)[s] = P[q_L][...P[q_1][s]...], a tuple over start symbols 0..7.

Function classes of a program (QUESTION.md "Measures"), checked disjoint for every task used:
  F12      product of some length-1 or length-2 program (supervised only under intermediate labels)
  F3train  product of a training length-3 program
  F3held   product of a held-out length-3 program
  novel    none of the above

uv run --locked python research/composition-c2/generalization/gen_task.py --task-id ops51000-ls51100
uv run --locked python research/composition-c2/generalization/gen_task.py --draw   # QUESTION.md draw rule
"""
import argparse
from collections import Counter
from itertools import permutations
import json
from pathlib import Path
import sys
import numpy as np

HERE = Path(__file__).resolve().parent
sys.path[:0] = [str(HERE.parent/'common'), str(HERE.parents[1]/'regimes'/'common')]
import c2task  # noqa: E402

N_SYM, N_OP = c2task.N_SYM, c2task.N_OP
CLASSES = ('F12', 'F3train', 'F3held', 'novel')


def products(P, length):
    """(programs in c2task.programs order, (n_programs, 8) product tables)."""
    progs = c2task.programs(length)
    d = c2task.rows(P, progs)
    return progs, d['states'][:, -1].reshape(len(progs), N_SYM)


def function_sets(P, train, held):
    """{class: set of product tuples} for the classes above (novel excluded)."""
    pr = {L: dict(zip(*(lambda q, t: (q, map(tuple, t)))(*products(P, L)))) for L in (1, 2, 3)}
    sets = dict(F12={*pr[1].values(), *pr[2].values()},
                F3train={pr[3][tuple(q)] for q in train}, F3held={pr[3][tuple(q)] for q in held})
    return sets


def classify(P, train, held, length):
    """Function class of every length-`length` program, in c2task.programs order."""
    sets = function_sets(P, train, held)
    _, tables = products(P, length)
    out = []
    for t in map(tuple, tables):
        hit = [c for c in CLASSES[:3] if t in sets[c]]
        assert len(hit) <= 1, f'function classes overlap for {t}: {hit}'
        out.append(hit[0] if hit else 'novel')
    return out


def group_order(P):
    """Order of the permutation group generated by the four ops (closure by breadth-first search)."""
    seen, frontier = {tuple(range(N_SYM))}, [tuple(range(N_SYM))]
    while frontier:
        new = []
        for g in frontier:
            for p in P:
                h = tuple(int(p[x]) for x in g)
                if h not in seen:
                    seen.add(h); new.append(h)
        frontier = new
    return len(seen)


def parity(p):
    return sum(1 for i in range(len(p)) for j in range(i+1, len(p)) if p[i] > p[j]) % 2


def identifiable(P, train):
    """Number of 4-tuples of permutations consistent with the 48 training FINAL tables (1 = the
    primitives are determined by final answers alone). Reviewer's r1 method: programs (a,b,c),
    (a',b,c) give Q_a' = Q_a o D for a known D, so every solution is Q_k = Q_0 o D_k; enumerate
    Q_0 over all 8! permutations and test every table."""
    _, t3 = products(P, 3)
    table = {q: t for q, t in zip(c2task.programs(3), t3)}
    inv = lambda p: np.argsort(p)
    D = {0: np.arange(N_SYM)}
    while len(D) < N_OP:  # spread known relative maps along shared (b, c) suffixes
        grew = False
        for q in train:
            for r in train:
                if q[1:] == r[1:] and q[0] in D and r[0] not in D:
                    # F_q = P_c P_b P_a ; F_r = P_c P_b P_a'  =>  P_a' = P_a o (F_q^-1 o F_r)
                    D[r[0]] = D[q[0]][inv(table[tuple(q)])[table[tuple(r)]]]; grew = True
        assert grew, 'slot-1 relation graph is disconnected'
    Q0 = np.array(list(permutations(range(N_SYM))))
    Q = [Q0[:, D[k]] for k in range(N_OP)]  # Q_k[s] = Q_0[D_k[s]]
    ok = np.ones(len(Q0), bool)
    for q in train:
        x = np.broadcast_to(np.arange(N_SYM), Q0.shape)
        for k in q:
            x = np.take_along_axis(Q[k], x, 1)
        ok &= (x == table[tuple(q)]).all(1)
    return int(ok.sum())


def structure(tid, max_len=6):
    """Everything QUESTION.md reports about one task (no model involved)."""
    T = c2task.load(tid)
    P, train, held = T['P'], T['train'], T['held']
    r1checks = c2task.r1.checks(P, train, held)
    nbr, nbr_all = c2task.neighbour_answerable(P, train, held)
    by_len = {}
    for L in range(1, max_len+1):
        progs, tables = products(P, L)
        groups = Counter(map(tuple, tables))
        cls = Counter(classify(P, train, held, L))
        by_len[L] = dict(programs=len(progs), distinct_products=len(groups),
                         programs_in_collision_groups=sum(n for n in groups.values() if n > 1),
                         largest_collision_group=max(groups.values()),
                         function_class_programs={c: cls.get(c, 0) for c in CLASSES})
    rep = Counter('distinct' if len(set(q)) == 3 else 'all-same' if len(set(q)) == 1 else
                  'a=b' if q[0] == q[1] else 'b=c' if q[1] == q[2] else 'a=c' for q in held)
    return dict(task_id=tid, task_seed_used=T['task_seed_used'], ops=P.tolist(), latin_square=T['L'].tolist(),
                held_out_programs=[list(q) for q in held], held_out_repetition_pattern=dict(rep),
                group_order=group_order(P), op_parities=[parity(p) for p in P],
                op_cycle_types=[o['cycle_type'] for o in r1checks['ops']], commuting_pairs=r1checks['commuting_pairs'],
                involutions=[o['op'] for o in r1checks['ops'] if o['involution']],
                identifiable_from_final_tables=identifiable(P, train),
                n_notN=int((~nbr).sum()), all_neighbours_are_training_rows=bool(nbr_all),
                coverage=r1checks['coverage'], heldout_baselines=r1checks['heldout_baselines'],
                row_overlap_train_heldout=r1checks['row_overlap_train_heldout'], by_length=by_len)


# --- QUESTION.md draw and split rule (fixed before any new draw was made) -----------------------
DRAW_SEEDS, SPLIT_SEEDS = range(63000, 63100), range(63100, 63200)
N_DRAWS, SPLITS_PER_DRAW = 2, 2


def draw_verdict(seed):
    """(accepted, reason) for permutation draw `seed`."""
    P, used = c2task.r1.draw_ops(seed)
    if used != seed:
        return False, f"r1 rule: seed {seed} has an identity or duplicate op (r1 would use {used})"
    tabs = [t for L in (1, 2, 3) for t in map(tuple, products(P, L)[1])]
    n_dup = len(tabs) - len(set(tabs))
    if n_dup:
        return False, f'{n_dup} coincidences among the 84 products of lengths 1-3'
    return True, 'accepted'


def draw_tasks():
    """Apply the rule in seed order; returns the decision log and the accepted task IDs."""
    log, draws = [], []
    for seed in DRAW_SEEDS:
        ok, why = draw_verdict(seed)
        log.append(dict(kind='draw', seed=seed, accepted=ok, reason=why))
        if ok:
            draws.append(seed)
            if len(draws) == N_DRAWS:
                break
    tasks, split_seeds = [], iter(SPLIT_SEEDS)
    for d in draws:
        squares = []
        while len(squares) < SPLITS_PER_DRAW:
            s = next(split_seeds)
            L = c2task.r1.split(s)[0]
            if any((L == M).all() for _, M in squares):
                log.append(dict(kind='split', draw=d, seed=s, accepted=False, reason='same Latin square as an accepted split of this draw'))
                continue
            T = c2task.load(c2task.task_id(d, s))
            cov = c2task.r1.checks(T['P'], T['train'], T['held'])['coverage']
            if not (cov['transitions_seen']['pos1 (s,a)'] == cov['transitions_seen']['pos2 (step1,b)'] ==
                    cov['transitions_seen']['pos3 (step2,c)'] == 32):
                log.append(dict(kind='split', draw=d, seed=s, accepted=False, reason='a transition is missing at some position'))
                continue
            log.append(dict(kind='split', draw=d, seed=s, accepted=True, reason='accepted'))
            squares.append((s, L)); tasks.append(c2task.task_id(d, s))
    return log, tasks


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--task-id', nargs='*', default=[])
    ap.add_argument('--draw', action='store_true', help='apply the draw/split rule and report every accepted task')
    ap.add_argument('--max-len', type=int, default=6)
    args = ap.parse_args()
    out = {}
    if args.draw:
        log, tasks = draw_tasks()
        out['decision_log'], out['accepted_tasks'] = log, tasks
        args.task_id = [*args.task_id, *tasks]
    out['structure'] = [structure(t, args.max_len) for t in args.task_id]
    print(json.dumps(out, indent=1, default=int))


if __name__ == '__main__':
    main()
