#!/usr/bin/env python3
"""Run accounting for e3: every claimed run in research/e3/plan.json with its terminal
registry status, and every registry event whose run ID is not claimed (there should be none).

uv run --locked python research/e3/coordinator/runs_table.py > research/e3/coordinator/RUNS.md
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
LANES = ('dynamics', 'mechanisms', 'audit', 'coordinator')


def main():
    plan = json.loads((ROOT/'research/e3/plan.json').read_text())
    events = {}
    for lane in LANES:
        path = ROOT/f'research/e3/{lane}/registry.jsonl'
        if path.exists():
            for line in path.read_text().splitlines():
                if line.strip():
                    e = json.loads(line)
                    events.setdefault(e['run_id'], []).append(dict(e, lane=lane))
    claimed = {r['run_id'] for r in plan['runs']}
    print('# e3 run accounting\n')
    print('Generated by `research/e3/coordinator/runs_table.py` from `research/e3/plan.json` and the lane registries. '
          'Status is the last registry event; "not launched" means claimed with no event.\n')
    print('| run ID | owner | start | updates | status | completed | published |')
    print('|---|---|---|---|---|---|---|')
    counts = {}
    for r in plan['runs']:
        ev = events.get(r['run_id'], [])
        last = ev[-1] if ev else {}
        status = last.get('status', 'not launched')
        counts[status] = counts.get(status, 0) + 1
        start = ('resume ' + r['source_run'] if 'resume' in r else
                 'edited weights from ' + r['source_run'] if 'init_weights' in r else 'init')
        steps = r.get('steps', plan['common']['steps'])
        pub = ROOT/f"research/e3/{r['owner']}/runs/{r['run_id']}"
        print(f"| `{r['run_id']}` | {r['owner']} | {start} | {steps:,} | {status} | "
              f"{last.get('completed_steps', '')} | {'yes' if pub.exists() else 'no'} |")
    print('\nTotals: ' + ', '.join(f'{k} {v}' for k, v in sorted(counts.items())) + f' (of {len(plan["runs"])} claimed).')
    stray = sorted(set(events) - claimed)
    print('\nRegistry events for unclaimed IDs: ' + (', '.join(f'`{s}`' for s in stray) if stray else 'none') + '.')


if __name__ == '__main__':
    main()
