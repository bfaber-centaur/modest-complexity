#!/usr/bin/env python3
"""Copy a run's small files and selected checkpoints into a Git-tracked lane
directory, with a manifest of SHA-256 hashes for every local file (published or not).

uv run --locked python publish_run.py runs/e1/RUN_ID research/LANE/runs
"""
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess

SMALL = ('config.json', 'runtime.json', 'metrics.jsonl', 'data.npz')
DEFAULT_STEPS = '0,1000,2000,5000,10000,20000,50000'


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('run_dir', type=Path)
    ap.add_argument('dest_root', type=Path)
    ap.add_argument('--steps', default=DEFAULT_STEPS,
                    help='Checkpoint steps to publish; the last and first-fit checkpoints are always added')
    args = ap.parse_args()
    runtime = json.loads((args.run_dir/'runtime.json').read_text())
    config = json.loads((args.run_dir/'config.json').read_text())
    checkpoints = sorted(args.run_dir.glob('checkpoint_*.npz'))
    available = {int(p.stem.split('_')[1]): p for p in checkpoints}
    wanted = {int(s) for s in args.steps.split(',') if s}
    if available:
        wanted.add(max(available))
    if runtime.get('first_interpolation') is not None:
        wanted.add(runtime['first_interpolation'])
    dest = args.dest_root/args.run_dir.name
    dest.mkdir(parents=True, exist_ok=True)
    for name in SMALL:
        if (args.run_dir/name).exists():
            shutil.copy2(args.run_dir/name, dest/name)
    for step in sorted(wanted & set(available)):
        shutil.copy2(available[step], dest/available[step].name)
    commit = subprocess.run(['git', 'rev-parse', 'HEAD'], capture_output=True, text=True).stdout.strip()
    manifest = dict(run_id=config.get('run_id') or args.run_dir.name, status=runtime.get('status'),
                    completed_steps=runtime.get('completed_steps'), producing_code_commit=config['runtime']['git_commit'],
                    producing_tree_dirty=bool(config['runtime']['git_status']), session_label=config.get('session_label'),
                    data_hashes=config.get('data_hashes'), published_from_commit=commit,
                    note='Checkpoints not published here are listed with hashes and can be regenerated by rerunning '
                         'the recorded command on the same code; a rerun is a reproducibility check, not a new seed.',
                    files={p.name: dict(sha256=sha256(p), bytes=p.stat().st_size, published=(dest/p.name).exists())
                           for p in sorted(args.run_dir.iterdir()) if p.is_file()})
    (dest/'manifest.json').write_text(json.dumps(manifest, indent=1)+'\n')
    print(dest, sum(f['published'] for f in manifest['files'].values()), 'files published')


if __name__ == '__main__':
    main()
